let LOCALE = 'en';

function setLocale(l) {
    LOCALE = (l === 'en' || I18N[l]) ? l : 'en';
    document.documentElement.lang = LOCALE;
}

function t(key) {
    const dict = I18N[LOCALE];
    return (dict && dict[key]) || key;
}

// Static markup: elements carrying data-i18n use their original English text
// as the key (captured on first pass so locale switches stay reversible).
function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim();
        el.textContent = t(el.dataset.i18nKey);
    });
}

// Prominent attributes translated explicitly (not via data-i18n).
function applyAttrI18n() {
    const search = document.getElementById('metaSearch');
    if (search) search.placeholder = t('Search keys & values…');
}

// ---- fleet wiring: carino-lang.js resolves the language and fires
// 'carino:langchange'; this file just follows it.
function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function applyI18n() {
    setLocale(currentFleetLang());
    applyStaticI18n();
    applyAttrI18n();
    // If a file is already loaded, re-render the viewer in the new language.
    try {
        if (typeof renderAll === 'function' && typeof current !== 'undefined' && current) renderAll();
    } catch (e) { /* viewer not ready — static pass is enough */ }
}

document.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);
